import 'server-only'
import { cols } from './db'

// Admin image uploads live in MongoDB (stored_uploads), not on disk: serverless hosts like Vercel have a
// read-only filesystem and lose files on redeploy. Documents store only the served URL, e.g.
// /api/uploads/products/1730000000000-ab12cd34ef56.webp, which GET /api/uploads/[folder]/[filename] serves.
export const UPLOAD_FOLDERS = ['products', 'gallery', 'pages', 'misc'] as const
export type UploadFolder = (typeof UPLOAD_FOLDERS)[number]
export const UPLOAD_PREFIX = '/api/uploads/'
export const MAX_UPLOAD_BYTES = 8 * 1024 * 1024

// Filenames are generated by POST /api/upload, so anything else (.., /, odd extensions) is rejected.
export const FILENAME = /^\d{13}-[a-f0-9]{16}\.(jpg|png|webp|gif)$/

/** "/api/uploads/products/x.webp" → { folder, filename }, or null for any other URL. */
export function parseUploadUrl(url: string) {
  if (!url.startsWith(UPLOAD_PREFIX)) return null
  const [folder, filename, ...rest] = url.slice(UPLOAD_PREFIX.length).split('/')
  if (rest.length || !UPLOAD_FOLDERS.includes(folder as UploadFolder) || !FILENAME.test(filename ?? '')) return null
  return { folder: folder as UploadFolder, filename }
}

/**
 * Deletes stored uploads no longer used by any product or banner. Call after saving a replace/remove,
 * so an image shared by two records is kept until the last one lets go of it.
 */
export async function deleteUnusedUploads(urls: string[]) {
  const c = await cols()
  for (const url of new Set(urls)) {
    const ref = parseUploadUrl(url)
    if (!ref) continue
    const [inProducts, inBanners] = await Promise.all([
      c.products.countDocuments({ 'images.src': url }, { limit: 1 }),
      c.banners.countDocuments({ src: url }, { limit: 1 }),
    ])
    if (!inProducts && !inBanners) await c.uploads.deleteOne(ref)
  }
}

/** Await after a successful save. Errors are logged, not thrown: a failed delete only leaves an orphaned file. */
export const cleanupUploads = (urls: string[]) =>
  deleteUnusedUploads(urls).catch((err) => console.error('[uploads] cleanup failed:', (err as Error).message))
